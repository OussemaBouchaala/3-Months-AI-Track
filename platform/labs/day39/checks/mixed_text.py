so = fn("script_of")
check("script_of", lambda: [so("سوسة"), so("Sahloul"), so("2026"), so("é"), so("_")] == ["arabic", "latin", "digit", "latin", "other"])
check("a digit+Arabic token is arabic", lambda: so("٣شقق") == "arabic" or so("3شقق") == "arabic")
sr = fn("script_ratio")
check("script_ratio counts word tokens", lambda: sr("شقة للبيع Sahloul 250") == {"arabic": 0.5, "latin": 0.25, "digit": 0.25})
ia = fn("is_arabizi")
check("is_arabizi finds Tunisian Arabizi", lambda: all(ia(t) for t in ["3andi", "chi9a", "7ata", "5ouya"]))
check("is_arabizi ignores plain numbers and words", lambda: not any(ia(t) for t in ["2026", "2", "sousse", "سوسة"]))
dl = fn("detect_lang")
check("Arabic text -> ar", lambda: dl("شقة للكراء قرب البحر") == "ar")
check("Arabizi text -> ar, even with plain words around", lambda: dl("3andi chi9a fi Sousse 9adech el kra") == "ar" and dl("3andi chi9a, 9adech?") == "ar")
check("one digit in a French listing isn't Arabizi", lambda: dl("Appartement S2 à louer pour la saison") == "fr")
check("French listing -> fr", lambda: dl("Appartement à louer avec 2 chambres, prix 900") == "fr")
check("English listing -> en", lambda: dl("Flat for rent near the beach, price 900") == "en")
check("a tie goes to fr", lambda: dl("Sahloul Sousse") == "fr")
sp = fn("split_runs")
check("split_runs groups scripts and skips digits", lambda: sp("شقة للبيع Appartement S+2 في سوسة") == [("arabic", "شقة للبيع"), ("latin", "Appartement S"), ("arabic", "في سوسة")])
